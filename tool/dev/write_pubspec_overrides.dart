/// Writes or removes a gitignored [pubspec_overrides.yaml] for sibling-repo
/// local dev (shared `xs/` layout: ../universal_storage/pkgs/<package>).
///
/// Usage (from your app repo root, e.g. vosges/):
///   dart run path/to/universal_storage/tool/dev/write_pubspec_overrides.dart write
///   dart run path/to/universal_storage/tool/dev/write_pubspec_overrides.dart delete
///
/// Options:
///   --prefix=../universal_storage/pkgs   Directory containing package folders
///   --include-mesh-closure             Also override convergence_session
///   --target=<path>                    Output file (default: pubspec_overrides.yaml)
import 'dart:io';

const _defaultPrefix = '../universal_storage/pkgs';

const _siblingPackages = [
  'universal_storage_chunks',
  'universal_storage_convergence',
  'universal_storage_interface',
  'universal_storage_local_db',
  'universal_storage_mesh',
  'universal_storage_mesh_transport',
  'universal_storage_sync',
  'universal_storage_world',
];

const _meshClosure = ['universal_storage_convergence_session'];

void main(List<String> args) {
  if (args.isEmpty || args.first == '--help' || args.first == '-h') {
    _usage();
    exit(0);
  }

  final command = args.first;
  var prefix = _defaultPrefix;
  var includeMeshClosure = false;
  var target = 'pubspec_overrides.yaml';

  for (final arg in args.skip(1)) {
    if (arg.startsWith('--prefix=')) {
      prefix = arg.substring('--prefix='.length);
    } else if (arg == '--include-mesh-closure') {
      includeMeshClosure = true;
    } else if (arg.startsWith('--target=')) {
      target = arg.substring('--target='.length);
    } else {
      print('Unknown argument: $arg');
      _usage();
      exit(64);
    }
  }

  switch (command) {
    case 'write':
      _write(
        target: target,
        prefix: prefix,
        packages: [
          ..._siblingPackages,
          if (includeMeshClosure) ..._meshClosure,
        ],
      );
    case 'delete':
      _delete(target);
    default:
      print('Unknown command: $command');
      _usage();
      exit(64);
  }
}

void _usage() {
  print('''
Commands:
  write   Create or overwrite pubspec_overrides.yaml with path overrides
  delete  Remove pubspec_overrides.yaml if present

Options:
  --prefix=../universal_storage/pkgs
  --include-mesh-closure
  --target=pubspec_overrides.yaml
''');
}

void _write({
  required String target,
  required String prefix,
  required List<String> packages,
}) {
  final normalizedPrefix = prefix.endsWith('/') ? prefix : '$prefix/';
  final buffer = StringBuffer();
  buffer.writeln('# Generated by universal_storage tool/dev/write_pubspec_overrides.dart');
  buffer.writeln('# Safe to delete; this file should stay gitignored in consumer repos.');
  buffer.writeln('dependency_overrides:');
  for (final name in packages) {
    buffer.writeln('  $name:');
    buffer.writeln('    path: $normalizedPrefix$name');
  }
  File(target).writeAsStringSync(buffer.toString());
  print('Wrote $target (${packages.length} overrides).');
}

void _delete(String target) {
  final file = File(target);
  if (file.existsSync()) {
    file.deleteSync();
    print('Deleted $target.');
  } else {
    print('No file at $target.');
  }
}
